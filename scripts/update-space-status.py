"""Regenerate docs/space-status.md from the kit matrix and deployment ledger.

Usage:
  python scripts/update-space-status.py
  python scripts/update-space-status.py --mark germany 04 deployed --release 2026-10-12
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.lib.matrix import LAYERS, ROOT, load_matrix  # noqa: E402

STATUS_PATH = ROOT / "docs" / "space-status.md"
LEDGER = ROOT / "deployment-state" / "ledger.json"


def load_ledger() -> dict:
    if not LEDGER.is_file():
        return {"marks": {}}
    return json.loads(LEDGER.read_text(encoding="utf-8"))


def save_ledger(ledger: dict) -> None:
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    LEDGER.write_text(json.dumps(ledger, indent=2) + "\n", encoding="utf-8")


def cell(space: dict, layer: str, mark: str | None) -> str:
    kits = (space.get("kits") or {}).get(layer)
    if layer not in (space.get("order") or []) and space.get("inventory") != "seeded":
        if space.get("inventory") == "awaiting-name":
            return "awaiting"
        if space.get("inventory") == "not-seeded":
            return "not seeded"
    if kits == []:
        return "n/a"
    if mark:
        return mark
    if kits:
        return "ready"
    if layer in (space.get("order") or []):
        return "planned"
    return "not seeded"


def render(matrix: dict, ledger: dict) -> str:
    marks = ledger.get("marks") or {}
    header = "| Space | API name | Prefix | " + " | ".join(LAYERS) + " | Status | Updated |"
    rule = "|---|---|---|" + "|".join(["---"] * len(LAYERS)) + "|---|---|"
    lines = [
        "# Space status",
        "",
        "Generated by `scripts/update-space-status.py`. Do not edit the table by hand.",
        "",
        "The sandbox data-spaces API returned 30 spaces. `unassigned` holds the 31st row until that name is supplied.",
        "",
        header,
        rule,
    ]
    for key, space in matrix["spaces"].items():
        space_marks = marks.get(key) or {}
        values = [cell(space, layer, space_marks.get(layer)) for layer in LAYERS]
        status = space_marks.get("_status") or space.get("inventory") or ""
        updated = space_marks.get("_date") or ""
        prefix = space.get("prefix") or ""
        lines.append(
            f"| {key} | {space.get('api_name') or ''} | {prefix} | "
            + " | ".join(values)
            + f" | {status} | {updated} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mark", nargs=3, metavar=("SPACE", "LAYER", "STATUS"))
    parser.add_argument("--release", default="")
    args = parser.parse_args()
    matrix = load_matrix()
    ledger = load_ledger()
    if args.mark:
        space, layer, status = args.mark
        if space not in matrix["spaces"]:
            print(f"Unknown space {space}", file=sys.stderr)
            return 1
        if layer not in LAYERS:
            print(f"Unknown layer {layer}", file=sys.stderr)
            return 1
        marks = ledger.setdefault("marks", {}).setdefault(space, {})
        marks[layer] = status
        marks["_status"] = status
        marks["_date"] = date.today().isoformat()
        if args.release:
            marks["_release"] = args.release
        save_ledger(ledger)
    STATUS_PATH.write_text(render(matrix, ledger), encoding="utf-8")
    print(f"Wrote {STATUS_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
